<?php

namespace Database\Seeders;

use App\Features\Artworks\Models\Artwork;
use App\Features\Auth\Enums\UserRole;
use App\Features\Auth\Enums\UserStatus;
use App\Features\Taxonomy\Models\ArtworkStyle;
use App\Features\Taxonomy\Models\ArtworkType;
use App\Models\User;
use Database\Seeders\Support\DemoArtworkPng;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use RuntimeException;

/**
 * Repair missing artwork media and add a self-contained, repeatable demo gallery.
 *
 * Existing users, their profiles, healthy artworks and uploaded files are kept.
 * Broken artworks are soft-deleted (recoverable); their records aren't truncated.
 * Only media stored under demo-artworks/ma-motion-v1 is generated by this seeder.
 */
final class MaMotionArtworkDemoSeeder extends Seeder
{
    private const PREFIX = 'demo-artworks/ma-motion-v1/';

    private const PIECES = [
        ['Amber Monolith', 'Golden light settles behind layered architectural planes. A study of scale, shadow and the warmth of an imagined city.', 'digital-art', 'minimal'],
        ['The Quiet Tide', 'A muted coastal horizon breaks into flowing teal bands beneath a solitary moon. An exploration of stillness and movement.', 'painting', 'contemporary'],
        ['Sculpted Earth', 'Terracotta shapes and a central arch recall stone, clay and ancient building forms. Warm contrasts meet a pared-back composition.', 'digital-art', 'geometric'],
        ['Botanical Memory', 'Oversized leaf silhouettes drift through a forest-green field. A poetic study of growth, balance and organic form.', 'illustration', 'organic'],
        ['Chromatic Orbit', 'Overlapping discs, diagonal accents and saturated blue create an energetic composition about rhythm and distance.', 'digital-art', 'abstract'],
        ['Blue Reverie', 'Soft color fields and a floating circular form hover over a winding horizon. A contemporary meditation on atmosphere.', 'painting', 'minimal'],
        ['Soft Geometry', 'Quiet architectural shapes are arranged against a low-lit sky. Subtle texture gives the geometry a tactile presence.', 'digital-art', 'modernist'],
        ['Desert Afterglow', 'Broad tidal curves, earthy tones and gentle contrasts suggest the last sunlight over an unfamiliar landscape.', 'painting', 'abstract'],
        ['Terra Passage', 'Layered archways frame a small world of warm clay and shadow. Negative space is an active part of the artwork.', 'digital-art', 'geometric'],
        ['Night Garden', 'Leaves gather around a delicate central stem. Deep greens and luminous accents evoke an imagined midnight garden.', 'illustration', 'organic'],
        ['Color in Motion', 'Contrasting fields and circular forms explore the tension between symmetry and movement.', 'digital-art', 'experimental'],
        ['Floating Light', 'A luminous sphere sits above a shifting field of color, capturing the sensation of a remembered sunset.', 'painting', 'contemporary'],
    ];

    public function run(): void
    {
        $makers = User::query()
            ->where('role', UserRole::Maker->value)
            ->where('status', UserStatus::Active->value)
            ->where(function ($query): void {
                $query->whereDoesntHave('makerProfile')
                    ->orWhereHas('makerProfile', static fn ($profile) => $profile->where('is_hidden', false));
            })
            ->orderBy('id')
            ->limit(8)
            ->get();

        if ($makers->isEmpty()) {
            throw new RuntimeException('No active, visible Maker exists. Existing users were not modified; create/activate a Maker before running this demo seeder.');
        }

        $this->call(MaMotionTaxonomySeeder::class);

        $disk = Storage::disk('public');
        $renderer = new DemoArtworkPng();
        $created = 0;
        $reused = 0;

        // Restore or generate genuine local PNG files, not external image URLs.
        // Each filename is stable, so rerunning the seeder is idempotent.
        foreach (self::PIECES as $index => $piece) {
            $path = $this->pathFor($index, $piece[0]);

            if (! $disk->exists($path) || $disk->size($path) < 1024) {
                $image = $renderer->render($index);
                if ($disk->put($path, $image) !== true) {
                    throw new RuntimeException('Could not write demo artwork image: '.$path);
                }
            }
        }

        // Preserve already seeded demo artworks and their IDs on reruns.
        $existingDemo = Artwork::query()
            ->with('primaryMedia')
            ->whereHas('media', static function ($query): void {
                $query->where('path', 'like', self::PREFIX.'%');
            })
            ->get()
            ->keyBy(function (Artwork $artwork): string {
                return (string) $artwork->primaryMedia?->path;
            });

        // Archive only artwork that has no usable media on any disk.
        // Healthy user uploads are never removed or overwritten.
        $broken = Artwork::query()
            ->with('media')
            ->whereDoesntHave('media', static function ($query): void {
                $query->where('path', 'like', self::PREFIX.'%');
            })
            ->get()
            ->filter(function (Artwork $artwork): bool {
                return $artwork->media->isEmpty()
                    || $artwork->media->every(static function ($media): bool {
                        try {
                            return ! Storage::disk($media->disk)->exists($media->path);
                        } catch (\Throwable) {
                            // Unknown external disks are not treated as broken.
                            return false;
                        }
                    });
            });

        $archivePath = null;
        if ($broken->isNotEmpty()) {
            $archivePath = 'backups/ma-motion-broken-artworks-'.now()->format('Ymd-His').'.json';
            $snapshot = $broken->map(static function (Artwork $artwork): array {
                return [
                    'artwork' => $artwork->getAttributes(),
                    'media' => $artwork->media->map->getAttributes()->all(),
                    'artwork_saves' => DB::table('artwork_saves')->where('artwork_id', $artwork->id)->get()->toArray(),
                    'show_artwork' => DB::table('show_artwork')->where('artwork_id', $artwork->id)->get()->toArray(),
                    'maker_profile_artwork_slots' => DB::table('maker_profile_artwork_slots')->where('artwork_id', $artwork->id)->get()->toArray(),
                ];
            })->all();

            if (Storage::disk('local')->put($archivePath, json_encode($snapshot, JSON_PRETTY_PRINT | JSON_THROW_ON_ERROR)) !== true) {
                throw new RuntimeException('Could not save backup manifest; no existing artwork was archived.');
            }

            // Soft-delete: metadata, saved relations and user accounts remain intact.
            foreach ($broken as $artwork) {
                $artwork->delete();
            }
        }

        foreach (self::PIECES as $index => [$title, $description, $typeSlug, $styleSlug]) {
            $path = $this->pathFor($index, $title);
            if ($existingDemo->has($path)) {
                $this->fillBrokenOrEmptyMakerInfoSlot($existingDemo->get($path));
                $reused++;
                continue;
            }

            $maker = $makers[$index % $makers->count()];
            $profile = $maker->makerProfile()->firstOrCreate(['user_id' => $maker->id]);

            $artwork = DB::transaction(function () use ($maker, $profile, $title, $description, $typeSlug, $styleSlug, $path, $index, $disk): Artwork {
                $artwork = Artwork::query()->create([
                    'maker_id' => $maker->id,
                    'title' => $title,
                    'description' => $description,
                    'artwork_type_id' => ArtworkType::query()->where('slug', $typeSlug)->value('id'),
                    'artwork_style_id' => ArtworkStyle::query()->where('slug', $styleSlug)->value('id'),
                    'location_id' => $profile->location_id,
                    'location_text' => $profile->location_text,
                    'moderation_status' => 'approved', // Curated admin demo content.
                    'is_visible' => true,
                    'sort_order' => $index + 1,
                ]);

                $artwork->media()->create([
                    'kind' => 'image',
                    'disk' => 'public',
                    'path' => $path,
                    'mime_type' => 'image/png',
                    'size_bytes' => $disk->size($path),
                    'width' => 640,
                    'height' => 800,
                    'alt_text' => $title.' — abstract artwork in the MA Motion demo gallery',
                    'sort_order' => 0,
                    'is_primary' => true,
                ]);

                // Demo artwork is admin-curated; mark only assigned Makers as
                // approved to match the existing one-time moderation behavior.
                if ($profile->artwork_approval_granted_at === null) {
                    $profile->forceFill(['artwork_approval_granted_at' => now()])->save();
                }

                return $artwork;
            });
            $this->fillBrokenOrEmptyMakerInfoSlot($artwork);
            $created++;
        }

        $this->command?->info('Demo artworks: '.$created.' created, '.$reused.' reused, '.$broken->count().' broken artworks safely archived.');
        if ($archivePath !== null) {
            $this->command?->info('Archived original metadata: storage/app/private/'.$archivePath);
        }
        $this->command?->info('All users and healthy artwork records were preserved. Artwork files: storage/app/public/'.self::PREFIX);
    }

    /**
     * Fill Maker Info slots 2–4 with usable demo artwork.
     * Existing user-selected slots with working images are never replaced.
     */
    private function fillBrokenOrEmptyMakerInfoSlot(Artwork $demo): void
    {
        $profile = $demo->maker->makerProfile;
        if ($profile === null) {
            return;
        }

        if ($profile->artworkSlots()->where('artwork_id', $demo->id)->exists()) {
            return;
        }

        foreach ([2, 3, 4] as $slot) {
            $assignment = $profile->artworkSlots()
                ->with('artwork.media')
                ->where('slot', $slot)
                ->first();

            if ($assignment !== null && $assignment->artwork !== null
                && $assignment->artwork->media->contains(static function ($media): bool {
                    try {
                        return Storage::disk($media->disk)->exists($media->path);
                    } catch (\Throwable) {
                        return true;
                    }
                })) {
                continue;
            }

            $profile->artworkSlots()->updateOrCreate(
                ['slot' => $slot],
                ['artwork_id' => $demo->id],
            );
            return;
        }
    }

    private function pathFor(int $index, string $title): string
    {
        return self::PREFIX.sprintf('%02d', $index + 1).'-'.Str::slug($title).'.png';
    }
}
